/**
 * Bundle the pure KEEL domain packages into a single ESM file the Deno Edge
 * runtime can import (PLAN §3.5.7): no npm publishing, no sloppy-imports.
 * Output is generated (git-ignored); run via `pnpm build:functions`.
 */
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'supabase', 'functions', '_shared', 'vendor');
mkdirSync(outDir, { recursive: true });

// Single virtual entry re-exporting every domain surface the functions need.
const entry = join(outDir, '.entry.ts');
writeFileSync(
  entry,
  [
    "export * from '@keel/ai';",
    "export * from '@keel/contracts';",
    "export * from '@keel/authz';",
    "export * from '@keel/ingest';",
    "export * from '@keel/ledger';",
    "export * from '@keel/exports';",
    "export * from '@keel/detectors';",
    "export * from '@keel/documents';",
    "export * from '@keel/plaid';",
    '',
  ].join('\n'),
);

await build({
  entryPoints: [entry],
  outfile: join(outDir, 'keel-domain.mjs'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2023',
  mainFields: ['module', 'main'],
  conditions: ['import'],
  alias: {
    '@keel/ai': join(root, 'packages', 'ai', 'src', 'index.ts'),
    '@keel/contracts': join(root, 'packages', 'contracts', 'src', 'index.ts'),
    '@keel/authz': join(root, 'packages', 'authz', 'src', 'index.ts'),
    '@keel/ingest': join(root, 'packages', 'ingest', 'src', 'index.ts'),
    '@keel/ledger': join(root, 'packages', 'ledger', 'src', 'index.ts'),
    '@keel/exports': join(root, 'packages', 'exports', 'src', 'index.ts'),
    '@keel/detectors': join(root, 'packages', 'detectors', 'src', 'index.ts'),
    '@keel/documents': join(root, 'packages', 'documents', 'src', 'index.ts'),
    '@keel/plaid': join(root, 'packages', 'providers', 'plaid', 'src', 'index.ts'),
  },
  // zod resolves from the workspace root install.
  nodePaths: [join(root, 'node_modules')],
  // zod is bundled in: the Edge functions get one self-contained artifact.
  external: [],
  banner: {
    js: '// GENERATED by scripts/build-functions.mjs — do not edit.',
  },
  logLevel: 'info',
});

console.log('functions vendor bundle written to supabase/functions/_shared/vendor/keel-domain.mjs');
