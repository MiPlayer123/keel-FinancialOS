/**
 * Bundle the pure KEEL domain packages into a single ESM file the Deno Edge
 * runtime can import (PLAN §3.5.7): no npm publishing, no sloppy-imports.
 * Output is generated (git-ignored); run via `pnpm build:functions`.
 */
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'supabase', 'functions', '_shared', 'vendor');
mkdirSync(outDir, { recursive: true });

// Single virtual entry re-exporting every domain surface the functions need.
const entry = join(outDir, '.entry.ts');
writeFileSync(
  entry,
  [
    "export * from '@keel/contracts';",
    "export * from '@keel/authz';",
    "export * from '@keel/ingest';",
    "export * from '@keel/ledger';",
    '',
  ].join('\n'),
);

await build({
  entryPoints: [entry],
  outfile: join(outDir, 'keel-domain.mjs'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2023',
  mainFields: ['module', 'main'],
  conditions: ['import'],
  // zod is bundled in: the Edge functions get one self-contained artifact.
  external: [],
  banner: {
    js: '// GENERATED by scripts/build-functions.mjs — do not edit.',
  },
  logLevel: 'info',
});

console.log('functions vendor bundle written to supabase/functions/_shared/vendor/keel-domain.mjs');
